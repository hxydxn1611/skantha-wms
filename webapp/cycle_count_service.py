class DiscrepancyType(str, Enum):
    """Canonical Cycle Count Discrepancy Types."""
    MATCH = "MATCH"
    SHORTAGE = "SHORTAGE"
    EXCESS = "EXCESS"
    EMPTY_BIN = "EMPTY_BIN"
    UNIDENTIFIED_MATERIAL = "UNIDENTIFIED_MATERIAL"
    AMBIGUOUS_IDENTITY = "AMBIGUOUS_IDENTITY"
    MULTIPLE_MATERIALS = "MULTIPLE_MATERIALS"
    NO_VISION_EVIDENCE = "NO_VISION_EVIDENCE"
    WRONG_MATERIAL = "WRONG_MATERIAL"


class CycleCountRecommendation(str, Enum):
    """Actionable recommendations generated by W.A.R.L.O.G."""
    NO_ACTION_REQUIRED = "NO_ACTION_REQUIRED"
    ADJUST_INVENTORY_SHORTAGE = "ADJUST_INVENTORY_SHORTAGE"
    ADJUST_INVENTORY_EXCESS = "ADJUST_INVENTORY_EXCESS"
    INVESTIGATE_MISSING_STOCK = "INVESTIGATE_MISSING_STOCK"
    CONFIRM_EMPTY_BIN = "CONFIRM_EMPTY_BIN"
    SCAN_BARCODE_OR_MANUAL_AUDIT = "SCAN_BARCODE_OR_MANUAL_AUDIT"
    MANUAL_VERIFICATION_REQUIRED = "MANUAL_VERIFICATION_REQUIRED"
    SEGREGATE_MIXED_STOCK = "SEGREGATE_MIXED_STOCK"
    RELOCATE_MISPLACED_STOCK = "RELOCATE_MISPLACED_STOCK"
    MANUAL_COUNT_REQUIRED = "MANUAL_COUNT_REQUIRED"


class ObservedMaterial:
    """Represents an observed physical material unit or batch in a storage bin."""
    def __init__(
        self,
        observed_id: Optional[str] = None,
        identity_status: str = "UNIDENTIFIED",
        material_type: str = "Component",
        quantity: int = 1,
        uom: str = "Units",
        confidence: float = 0.0,
        matched_sku: Optional[str] = None,
        matched_name: Optional[str] = None,
        barcode_or_qr: Optional[str] = None,
        is_ambiguous: bool = False,
        raw_evidence: Optional[Dict[str, Any]] = None
    ):
        self.observed_id = observed_id
        self.identity_status = identity_status  # VALIDATED, UNIDENTIFIED, AMBIGUOUS, UNREGISTERED
        self.material_type = material_type      # Glass, Steel Rod, Fasteners, Carton, etc.
        self.quantity = max(0, quantity)
        self.uom = uom
        self.confidence = confidence
        self.matched_sku = matched_sku
        self.matched_name = matched_name
        self.barcode_or_qr = barcode_or_qr
        self.is_ambiguous = is_ambiguous
        self.raw_evidence = raw_evidence or {}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "observed_id": self.observed_id,
            "identity_status": self.identity_status,
            "material_type": self.material_type,
            "quantity": self.quantity,
            "uom": self.uom,
            "confidence": round(self.confidence, 3),
            "matched_sku": self.matched_sku,
            "matched_name": self.matched_name,
            "barcode_or_qr": self.barcode_or_qr,
            "is_ambiguous": self.is_ambiguous,
            "raw_evidence": self.raw_evidence
        }



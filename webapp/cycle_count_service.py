"""
W.A.R.L.O.G. / Skandha WMS AI Vision & Tracking Master
Part 7 — Cycle Count AI & Bin Discrepancy Auditing Service

Material-agnostic AI observation and discrepancy recommendation service
for automotive warehouse storage bins (glass, small parts, rods, packaged components).

Key Architectural Principles:
1. WMS Bins, Inventory, and SKU Masters remain authoritative.
2. W.A.R.L.O.G. provides physical observation evidence and discrepancy recommendations.
3. ZERO automatic inventory mutations from vision. Passive analysis leaves inventory untouched.
4. The ONLY inventory mutation path is an explicit operator/WMS Cycle Count action.
5. Material-agnostic: Does not assume all materials are boxes. Supports glass, rods, small parts, cartons.
6. Uses barcode/QR/OCR/tag identity where available; does not rely on visual appearance alone for SKU identity.
7. Handles 8 core discrepancy scenarios:
   - MATCH (matching quantity)
   - SHORTAGE (observed < expected)
   - EXCESS (observed > expected)
   - EMPTY_BIN (expected > 0, observed == 0, or both 0)
   - UNIDENTIFIED_MATERIAL (items present without resolvable barcode/identity)
   - AMBIGUOUS_IDENTITY (conflicting candidate reads or multiple SKU matches)
   - MULTIPLE_MATERIALS (co-mingled/mixed distinct SKUs in bin)
   - NO_VISION_EVIDENCE (no camera coverage, frame feeds, or tracked items)
"""


# 2. CYCLE COUNT AUDIT SERVICE
# ============================================================================

class CycleCountAuditService:
    """
    Evaluates physical storage bins against authoritative WMS inventory
    using W.A.R.L.O.G. vision evidence, material traceability, and barcode/OCR reads.
    Strictly read-only during perception. Zero database writes during evaluation.
    """

    def __init__(self):
        self.traceability_service = get_material_traceability_service()
        self.validation_service = get_validation_service()
        logger.info("CycleCountAuditService initialized.")

    def get_bin_inventory(self, bin_id: str) -> Dict[str, Any]:
        """
        Retrieves authoritative WMS inventory for a bin from the database.
        Returns bin details, expected items list, and total expected quantity.
        """
        conn = get_db()
        try:
            bin_row = conn.execute("SELECT * FROM bins WHERE bin_id = ?", (bin_id,)).fetchone()
            bin_details = dict(bin_row) if bin_row else {
                "bin_id": bin_id,
                "zone": "General",
                "max_volume": 100.0,
                "max_weight": 1000.0,
                "status": "Active"
            }

            cursor = conn.execute("""
                SELECT i.id, i.bin_id, i.sku_id, i.quantity, i.batch_number, i.expiry_date,
                       i.vendor, i.received_date, s.name as sku_name, s.category,
                       s.unit_volume, s.unit_weight
                FROM inventory i
                LEFT JOIN skus s ON i.sku_id = s.sku_id
                WHERE i.bin_id = ?
                ORDER BY i.received_date DESC
            """, (bin_id,))
            items = [dict(r) for r in cursor.fetchall()]
            total_qty = sum(item.get("quantity", 0) for item in items)
            
            return {
                "bin_id": bin_id,
                "bin_details": bin_details,
                "items": items,
                "total_quantity": total_qty,
                "distinct_skus": list(set(it["sku_id"] for it in items if it.get("sku_id")))
            }
        finally:
            conn.close()

    def gather_vision_evidence(self, bin_id: str) -> Dict[str, Any]:
        """
        Extracts physical vision observations and traceability records
        associated with the given bin_id.
        """
        observed_materials: List[ObservedMaterial] = []
        monitoring_cameras: List[str] = []

        # 1. Identify cameras configured or positioned for this bin
        conn = get_db()
        try:
            cam_rows = conn.execute("""
                SELECT camera_id, camera_code, name, location, bin_id 
                FROM cameras 
                WHERE bin_id = ? OR location = ? OR location LIKE ?
            """, (bin_id, bin_id, f"%{bin_id}%")).fetchall()
            for r in cam_rows:
                monitoring_cameras.append(r["camera_id"])
        except Exception as e:
            logger.warning("Error looking up bin monitoring cameras: %s", e)
        finally:
            conn.close()

        # 2. Check active in-memory MaterialTraceability records
        # Scan materials whose destination or associated_bins points to bin_id
        active_traces = getattr(self.traceability_service, "materials", {})
        for mat_id, record in active_traces.items():
            dest = getattr(record, "destination", None) or {}
            dest_bin = dest.get("identity_id") or dest.get("track_id")
            
            # Also check associated_bins list
            matched_bin_assoc = any(
                (b.get("identity_id") == bin_id or b.get("track_id") == bin_id)
                for b in getattr(record, "associated_bins", [])
            )

            if dest_bin == bin_id or matched_bin_assoc:
                mat_type = getattr(record, "object_class", "Component")
                ident_val = getattr(record, "identity_id", None)
                ident_status = getattr(record, "identity_status", "UNIDENTIFIED")
                barcode = getattr(record, "barcode_value", None) or ident_val
                
                # Check SKU lookup for name / category
                matched_sku = ident_val if ident_status == "VALIDATED" else None
                sku_info = self._lookup_sku_info(matched_sku) if matched_sku else None
                
                observed_materials.append(ObservedMaterial(
                    observed_id=ident_val or mat_id,
                    identity_status=ident_status,
                    material_type=sku_info.get("category") if sku_info else mat_type,
                    quantity=1,
                    uom="Units",
                    confidence=getattr(record, "confidence", 0.90),
                    matched_sku=matched_sku,
                    matched_name=sku_info.get("name") if sku_info else None,
                    barcode_or_qr=barcode,
                    is_ambiguous=(ident_status == "AMBIGUOUS"),
                    raw_evidence={"trace_id": getattr(record, "trace_id", None), "material_id": mat_id}
                ))

        has_evidence = len(observed_materials) > 0 or len(monitoring_cameras) > 0
        return {
            "has_vision_evidence": has_evidence,
            "monitoring_cameras": monitoring_cameras,
            "observed_materials": observed_materials
        }

    def _lookup_sku_info(self, sku_id: Optional[str]) -> Optional[Dict[str, Any]]:
        """Reads SKU master metadata without mutating database."""
        if not sku_id:
            return None
        conn = get_db()
        try:
            row = conn.execute("SELECT sku_id, name, description, category, unit_weight, unit_volume FROM skus WHERE UPPER(sku_id) = ?", (sku_id.upper(),)).fetchone()
            return dict(row) if row else None
        finally:
            conn.close()

    def evaluate_bin(
        self,
        bin_id: str,
        observation_override: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Cross-references observed physical material against authoritative WMS bin inventory.
        Generates discrepancy diagnosis, recommendation, and explanation.
        Pure calculation — zero database writes.

        observation_override may supply:
          - 'has_vision_evidence': bool
          - 'observed_materials': List[dict or ObservedMaterial]
          - 'monitoring_cameras': List[str]
        """
        # 1. Authoritative WMS Inventory
        wms_data = self.get_bin_inventory(bin_id)
        expected_items = wms_data["items"]
        expected_qty = wms_data["total_quantity"]
        expected_skus = wms_data["distinct_skus"]

        # 2. Vision Evidence Collection
        if observation_override is not None:
            has_evidence = observation_override.get("has_vision_evidence", True)
            raw_obs = observation_override.get("observed_materials", [])
            monitoring_cams = observation_override.get("monitoring_cameras", [])
            
            observed_materials: List[ObservedMaterial] = []
            for item in raw_obs:
                if isinstance(item, ObservedMaterial):
                    observed_materials.append(item)
                elif isinstance(item, dict):
                    observed_materials.append(ObservedMaterial(
                        observed_id=item.get("observed_id") or item.get("sku_id"),
                        identity_status=item.get("identity_status", "VALIDATED" if item.get("sku_id") else "UNIDENTIFIED"),
                        material_type=item.get("material_type", "Component"),
                        quantity=item.get("quantity", 1),
                        uom=item.get("uom", "Units"),
                        confidence=item.get("confidence", 0.95),
                        matched_sku=item.get("matched_sku") or item.get("sku_id"),
                        matched_name=item.get("matched_name") or item.get("name"),
                        barcode_or_qr=item.get("barcode_or_qr"),
                        is_ambiguous=item.get("is_ambiguous", False) or item.get("identity_status") == "AMBIGUOUS",
                        raw_evidence=item.get("raw_evidence")
                    ))
            vision_evidence = {
                "has_vision_evidence": has_evidence,
                "monitoring_cameras": monitoring_cams,
                "observed_materials": observed_materials
            }
        else:
            vision_evidence = self.gather_vision_evidence(bin_id)

        has_evidence = vision_evidence["has_vision_evidence"]
        observed_list: List[ObservedMaterial] = vision_evidence["observed_materials"]

        # Calculate observed metrics
        total_observed_qty = sum(m.quantity for m in observed_list)
        validated_skus = list(set(m.matched_sku for m in observed_list if m.matched_sku and m.identity_status == "VALIDATED"))
        has_ambiguous = any(m.is_ambiguous or m.identity_status == "AMBIGUOUS" for m in observed_list)
        has_unidentified = any(m.identity_status in ("UNIDENTIFIED", "UNREGISTERED") for m in observed_list)

        # 3. Discrepancy Evaluation Matrix
        discrepancy_type = DiscrepancyType.MATCH
        recommendation = CycleCountRecommendation.NO_ACTION_REQUIRED
        explanation = ""
        suggested_qty: Optional[int] = None
        is_action_required = False

        # Case 1: No Vision Evidence
        if not has_evidence:
            discrepancy_type = DiscrepancyType.NO_VISION_EVIDENCE
            recommendation = CycleCountRecommendation.MANUAL_COUNT_REQUIRED
            explanation = (
                f"No active camera streams or vision tracking sessions covering bin '{bin_id}'. "
                f"WMS ledger indicates {expected_qty} units of SKU {expected_skus or ['N/A']}. "
                "Physical inspection / manual count is required."
            )
            is_action_required = True
            suggested_qty = None

        # Case 2: Ambiguous Identity
        elif has_ambiguous:
            discrepancy_type = DiscrepancyType.AMBIGUOUS_IDENTITY
            recommendation = CycleCountRecommendation.MANUAL_VERIFICATION_REQUIRED
            explanation = (
                f"Vision observed material in bin '{bin_id}', but identity is ambiguous with conflicting barcode/OCR reads. "
                "Manual barcode scanning and operator verification required before adjusting ledger."
            )
            is_action_required = True
            suggested_qty = None

        # Case 3: Unidentified Material (Physical stock present, but no readable barcode / part tag)
        elif has_unidentified and total_observed_qty > 0:
            discrepancy_type = DiscrepancyType.UNIDENTIFIED_MATERIAL
            recommendation = CycleCountRecommendation.SCAN_BARCODE_OR_MANUAL_AUDIT
            explanation = (
                f"Vision observed {total_observed_qty} physical items in bin '{bin_id}', but their barcodes/tags could not be resolved. "
                "Scan barcodes or perform manual part identification."
            )
            is_action_required = True
            suggested_qty = None

        # Case 4: Multiple Materials / Mixed SKUs in Bin
        elif len(validated_skus) > 1 and len(expected_skus) <= 1:
            discrepancy_type = DiscrepancyType.MULTIPLE_MATERIALS
            recommendation = CycleCountRecommendation.SEGREGATE_MIXED_STOCK
            explanation = (
                f"Multiple distinct automotive materials observed in bin '{bin_id}': {validated_skus}. "
                f"WMS only expects single SKU {expected_skus}. Possible co-mingled or misplaced components."
            )
            is_action_required = True
            suggested_qty = None

        # Case 5: Empty Bin in Physical Observation (0 items observed)
        elif total_observed_qty == 0:
            if expected_qty == 0:
                discrepancy_type = DiscrepancyType.MATCH
                recommendation = CycleCountRecommendation.CONFIRM_EMPTY_BIN
                explanation = f"Bin '{bin_id}' is empty in both WMS inventory records and physical vision observation."
                suggested_qty = 0
                is_action_required = False
            else:
                discrepancy_type = DiscrepancyType.EMPTY_BIN
                recommendation = CycleCountRecommendation.INVESTIGATE_MISSING_STOCK
                delta = 0 - expected_qty
                explanation = (
                    f"WMS ledger records {expected_qty} units of SKU {expected_skus} in bin '{bin_id}', "
                    "but physical bin is observed completely empty (Deficit of "
                    f"{expected_qty} units). Immediate investigation required."
                )
                suggested_qty = 0
                is_action_required = True

        # Case 6: Wrong Material / SKU Mismatch
        elif len(validated_skus) == 1 and expected_skus and validated_skus[0] not in expected_skus:
            discrepancy_type = DiscrepancyType.WRONG_MATERIAL
            recommendation = CycleCountRecommendation.RELOCATE_MISPLACED_STOCK
            obs_sku = validated_skus[0]
            explanation = (
                f"Misplaced stock detected: WMS expected SKU {expected_skus} in bin '{bin_id}', "
                f"but physical items belong to SKU '{obs_sku}'."
            )
            is_action_required = True
            suggested_qty = None

        # Case 7: Quantity Comparison (Matching, Shortage, or Excess)
        else:
            delta = total_observed_qty - expected_qty
            suggested_qty = total_observed_qty

            if delta == 0:
                discrepancy_type = DiscrepancyType.MATCH
                recommendation = CycleCountRecommendation.NO_ACTION_REQUIRED
                explanation = (
                    f"Physical count ({total_observed_qty} units) perfectly matches WMS ledger ({expected_qty} units) "
                    f"for bin '{bin_id}'."
                )
                is_action_required = False

            elif delta < 0:
                discrepancy_type = DiscrepancyType.SHORTAGE
                recommendation = CycleCountRecommendation.ADJUST_INVENTORY_SHORTAGE
                explanation = (
                    f"Inventory shortage detected in bin '{bin_id}': WMS records {expected_qty} units, "
                    f"but vision observed only {total_observed_qty} units (Shortage of {abs(delta)} units)."
                )
                is_action_required = True

            else:  # delta > 0
                discrepancy_type = DiscrepancyType.EXCESS
                recommendation = CycleCountRecommendation.ADJUST_INVENTORY_EXCESS
                explanation = (
                    f"Inventory excess detected in bin '{bin_id}': WMS records {expected_qty} units, "
                    f"but vision observed {total_observed_qty} units (Surplus of {delta} units)."
                )
                is_action_required = True

        delta_qty = total_observed_qty - expected_qty if has_evidence else 0

        return {
            "success": True,
            "bin_id": bin_id,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "wms_inventory": {
                "bin_details": wms_data["bin_details"],
                "items": expected_items,
                "total_quantity": expected_qty,
                "distinct_skus": expected_skus
            },
            "vision_evidence": {
                "has_vision_evidence": has_evidence,
                "monitoring_cameras": vision_evidence.get("monitoring_cameras", []),
                "observed_materials": [m.to_dict() for m in observed_list],
                "total_observed_qty": total_observed_qty,
                "validated_skus": validated_skus,
                "has_ambiguous": has_ambiguous,
                "has_unidentified": has_unidentified
            },
            "discrepancy": {
                "type": discrepancy_type.value,
                "expected_qty": expected_qty,
                "observed_qty": total_observed_qty if has_evidence else None,
                "delta": delta_qty if has_evidence else None,
                "recommendation": recommendation.value,
                "explanation": explanation,
                "is_action_required": is_action_required,
                "suggested_cycle_count_qty": suggested_qty
            }
        }

    def audit_bin(self, bin_id: str, observation_override: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Alias for evaluate_bin to support Part 13 Controlled Actions."""
        return self.evaluate_bin(bin_id, observation_override)


